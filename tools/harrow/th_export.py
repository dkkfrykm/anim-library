"""Export phase6 TH outputs to Harrow modules (CONTRACTS §5).
- renames Sky_<Rig>_<Slot> -> <Rig>_<Slot>, merges idle modules, fixes loops (Idle/Stance/Walk/Downed loop 0..n, others none)
- writes src/ReplicatedStorage/Assets/Anim/Clips/<Rig>.lua and Assets/Anim/ClipTimings.lua (seconds, marker names agreed with COMBAT)
Usage: python -E -P th_export.py <phase6 out dir> [more dirs...]
"""
import sys, os, re, glob, json

SRC = r'C:\Users\mytwo\harrow\src\ReplicatedStorage\Assets\Anim'
LOOPS = {'Idle', 'Stance', 'Stance_2H', 'Aim', 'Walk', 'Run', 'Downed', 'Sit', 'Sit2', 'SitGround', 'CampInspect', 'CampCraft', 'CampBandage', 'CampRest', 'CampWarm', 'CampSleep', 'CampMeditate'}
RELEASE = ('Cast', 'Heal', 'Throw')
FPS = 60


def fields(body):
    """split top-level k=v pairs of a Lua table body (values are numbers, {..}, "..", [[..]])"""
    out, i, n = [], 0, len(body)
    while i < n:
        m = re.match(r'\s*([A-Za-z_]\w*)=', body[i:])
        if not m:
            break
        k = m.group(1); i += m.end()
        if body.startswith('[[', i):
            j = body.index(']]', i) + 2
        elif body[i] == '{':
            j = body.index('}', i) + 1
        elif body[i] == '"':
            j = body.index('"', i + 1) + 1
        else:
            j = i
            while j < n and body[j] not in ',': j += 1
        out.append((k, body[i:j])); i = j
        if i < n and body[i] == ',': i += 1
    return out


def main():
    clips = {}
    for d in sys.argv[1:]:
        for f in sorted(glob.glob(os.path.join(d, 'Clips_*.lua'))):
            for line in open(f, encoding='utf-8'):
                m = re.match(r'(Sky_)?([A-Za-z0-9]+)_([A-Za-z0-9_]+)=\{(.*)\},?\s*$', line.strip())
                if not m:
                    continue
                rig, slot = m.group(2), m.group(3)
                if m.group(1) and slot == 'Idle':
                    slot = 'Stance'  # phase6 idle = combat guard loop; the relaxed Idle is authored (th_authored.py)
                clips[(rig, slot)] = fields(m.group(4))
    by, timings = {}, {}
    for (rig, slot), fl in sorted(clips.items()):
        d = dict(fl)
        n = int(d['n'])
        if slot in LOOPS:
            fl = [(k, v) for k, v in fl if k not in ('la', 'lb', 'i', 'sw')] + [('la', '0'), ('lb', str(n))]
        else:
            fl = [(k, v) for k, v in fl if k not in ('la', 'lb')]
        name = '%s_%s' % (rig, slot)
        by.setdefault(rig, []).append('%s={%s}' % (name, ','.join('%s=%s' % kv for kv in fl)))
        d = dict(fl)
        mk = {}
        if slot not in LOOPS:
            w, r = int(d.get('w', 0)), int(d.get('r', n))
            imp = [int(x) for x in re.findall(r'\d+', d.get('i', '{}'))]
            mk['Telegraph'] = round(w / FPS, 4); mk['Windup'] = round(w / FPS, 4)
            for k, f in enumerate(imp):
                mk['Impact' if k == 0 else 'Impact%d' % (k + 1)] = round(f / FPS, 4)
            mk['Recover'] = round(r / FPS, 4)
            if slot.startswith(RELEASE) and imp:
                mk['Release'] = mk['Impact']
        timings[name] = dict(length=round(n / FPS, 4), loop=slot in LOOPS, markers=mk)
    for d in sys.argv[1:]:  # footstep contacts (AUDIO) for loops
        fp = os.path.join(d, 'footsteps.json')
        if os.path.exists(fp):
            for name, fs in json.load(open(fp)).items():
                if name in timings:
                    for k, frames in fs.items():
                        timings[name]['markers'][k] = '{' + ','.join(str(round(f / FPS, 4)) for f in frames) + '}'
    os.makedirs(os.path.join(SRC, 'Clips'), exist_ok=True)
    for rig, items in by.items():
        src = ('-- ReplicatedStorage.Assets.Anim.Clips.%s (ASSETS, generated by harrow/anim/tools/th_export.py; do not hand edit)\n'
               '-- CONTRACTS §5 raw clips @60fps. Built from raw Skyrim HKX components + authored per-class poses (anim/tools/p6_bth.py).\nreturn {\n%s\n}\n') % (rig, ',\n'.join(items))
        open(os.path.join(SRC, 'Clips', rig + '.lua'), 'w', newline='\n').write(src)
        print(rig, len(items))
    lines = ['-- ReplicatedStorage.Assets.Anim.ClipTimings (ASSETS, generated). Seconds from clip start at speed 1.',
             '-- markers: Telegraph, Windup, Impact, Impact2..N, Recover, Release. Same source data as the Clips modules.', 'return {']
    for name, t in sorted(timings.items()):
        mk = ', '.join('%s=%s' % (k, v) for k, v in t['markers'].items())
        lines.append('\t%s = {length=%s, loop=%s, markers={%s}},' % (name, t['length'], str(t['loop']).lower(), mk))
    lines.append('}')
    open(os.path.join(SRC, 'ClipTimings.lua'), 'w', newline='\n').write('\n'.join(lines) + '\n')
    json.dump(timings, open(os.path.join(SRC, 'ClipTimings.json'), 'w'), indent=1)
    print('timings', len(timings))


if __name__ == '__main__':
    main()
