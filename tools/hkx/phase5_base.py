# Rebuild the 52 base Sky style clips (Clips_Sky<Style>) as renamed copies of QA-passed phase-5 power clips.
import re, os, sys, json
D = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "out", "phase5")
SRC = {  # style: [power order to search per slot]
    "Fighter": ["brawler", "boxer", "karate"], "Kick": ["kicker"], "Blade": ["demonhunter", "soulblade", "soulrequiem"],
    "Titan": ["titanstrength", "ironbody"], "Beast": ["beastform", "dragonshift"], "Mystic": ["chakra", "chakramaster"],
    "Spirit": ["psychic", "astraloverlord"],
}
SLOTS = {"Fighter": "M1_1 M1_2 M1_3 M1_4 Bolt Blast Burst Dash", "Kick": "M1_1 M1_2 M1_3 M1_4",
         "Blade": "M1_1 M1_2 M1_3 M1_4 Bolt Blast Burst Dash Ult", "Titan": "M1_1 M1_2 M1_3 M1_4 Bolt Blast Burst Dash",
         "Beast": "M1_1 M1_2 M1_3 M1_4 Bolt Blast Burst Dash", "Mystic": "M1_1 M1_2 M1_3 M1_4 Bolt Blast Burst Dash",
         "Spirit": "Bolt Blast Burst Dash"}
ULT = {"Leap": "titanstrength", "Beam": "supernovagod", "Nuke": "absoluteinfinity"}
FALLBACK = {"Bolt": ["Bolt", "Blast", "M1_4"], "Blast": ["Blast", "Bolt", "Burst"], "Burst": ["Burst", "Ult", "Blast"], "Ult": ["Ult", "Burst"], "Dash": ["Dash"]}
cache = {}
def clips(pid):
    if pid not in cache:
        t = open(os.path.join(D, "Clips_SkyP_%s.lua" % pid)).read()
        cache[pid] = dict(re.findall(r"^Sky_%s_(\w+?)=(\{.*\}),?$" % pid, t, re.M))
    return cache[pid]
def find(pids, slot):
    for s in FALLBACK.get(slot, [slot]):
        for p in pids:
            if s in clips(p): return p, s, clips(p)[s]
    raise KeyError((pids, slot))
mods = {st: [] for st in list(SRC) + ["Ult"]}; prov = {}
for st, pids in SRC.items():
    for slot in SLOTS[st].split():
        p, s, body = find(pids, slot); mods[st].append(("Sky_%s_%s" % (st, slot), body)); prov["Sky_%s_%s" % (st, slot)] = "Sky_%s_%s" % (p, s)
for k, p in ULT.items():
    _, s, body = find([p], "Ult"); mods["Ult"].append(("Sky_Ult_" + k, body)); prov["Sky_Ult_" + k] = "Sky_%s_%s" % (p, s)
n = 0
for st, items in mods.items():
    with open(os.path.join(D, "base", "Clips_Sky%s.lua" % st), "w", newline="\n") as f:
        f.write("-- AUTO-GENERATED by soulbound/skyrim/tools/phase5_base.py: base Sky style clips, copies of QA-passed phase-5 power clips.\nreturn {\n")
        for name, body in items: f.write("%s=%s,\n" % (name, body)); n += 1
        f.write("}\n")
json.dump(prov, open(os.path.join(D, "base", "provenance.json"), "w"), indent=1)
print("base clips", n)
