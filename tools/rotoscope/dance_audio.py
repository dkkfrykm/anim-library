"""Dance music: each dance's source-video audio cut to EXACTLY the clip's loop window (mocap_clips/<id>.json log.loop = [i, j] source
frames, fps) with the same seam blend as the motion (mocap_bake.crop_blend: the last B = round(fps*.5) frames crossfade (smoothstep) into
the B frames before i), so audio and dance loop together seamlessly. Encoded Opus/Ogg (96 kb/s stereo) and embedded base64 in
web/assets/anims/dance_audio.js (window.RB_DANCE_AUDIO = {id: {dur, data}}), since the game runs from file:// (no fetch).
Personal-use build (user's own choice of reference videos). Usage: <python with numpy> tools/roto/dance_audio.py <reiko_breed dir> [ids]"""
import sys, os, json, glob, base64, subprocess, tempfile
import numpy as np
D = os.path.abspath(sys.argv[1]); ONLY = sys.argv[2].split(',') if len(sys.argv) > 2 else None
FF = os.environ.get('FFMPEG', r'C:/Users/mytwo/AppData/Local/Temp/claude/532a5d2f69a76e11/95d684a3-cf60-44a6-a967-cafb84428bc5/scratchpad/ffbin/ffmpeg.exe')
SRC = r'C:/Users/mytwo/OneDrive/Desktop/HalfAnEye_HANDOFF/dance_sources'; SR = 48000
OUT = os.path.join(D, 'web', 'assets', 'anims', 'dance_audio.js')

def decode(path):
    raw = subprocess.run([FF, '-v', 'error', '-i', path, '-vn', '-ac', '2', '-ar', str(SR), '-f', 'f32le', '-'], capture_output=True, check=True).stdout
    return np.frombuffer(raw, np.float32).reshape(-1, 2).copy()

def cut(a, i, j, fps, B, n):
    """samples for clip frames [i, j) (n frames), last B frames crossfaded into frames [i-B, i) like the motion"""
    s0 = int(round(i / fps * SR)); L = int(round(n / fps * SR)); seg = a[s0:s0 + L].copy()
    if len(seg) < L: seg = np.concatenate([seg, np.zeros((L - len(seg), 2), np.float32)])
    bl = int(round(B / fps * SR)); pre = a[max(0, s0 - bl):s0]
    if len(pre) == bl and bl > 0:
        w = (np.arange(bl) + 1) / (bl + 1); w = (w * w * (3 - 2 * w))[:, None]; seg[L - bl:] = seg[L - bl:] * (1 - w) + pre * w
    return seg

def encode(seg):
    with tempfile.TemporaryDirectory() as td:
        raw = os.path.join(td, 'a.f32'); out = os.path.join(td, 'a.ogg'); seg.astype(np.float32).tofile(raw)
        subprocess.run([FF, '-v', 'error', '-f', 'f32le', '-ar', str(SR), '-ac', '2', '-i', raw, '-c:a', 'libopus', '-b:a', '96k', out], check=True)
        return open(out, 'rb').read()

def main():
    old = {}
    if os.path.exists(OUT):
        s = open(OUT, encoding='utf-8').read(); k = s.index('window.RB_DANCE_AUDIO=') + 22; old = json.JSONDecoder().raw_decode(s[k:])[0]
    res = dict(old)
    for cp in sorted(glob.glob(os.path.join(D, 'tools', 'roto', 'mocap_clips', 'dance_*.json'))):
        did = os.path.basename(cp)[:-5]
        if ONLY and did not in ONLY: continue
        v = glob.glob(os.path.join(SRC, did + '__*'))
        if not v: print(did, 'no source video'); continue
        C = json.load(open(cp)); log = C['log']; i, j = log['loop']; fps = float(log['fps']); n = C['clip']['n']; B = int(round(fps * .5))
        try: a = decode(v[0])
        except subprocess.CalledProcessError: print(did, 'no audio stream'); continue
        seg = cut(a, i, j, fps, B, n); pk = float(np.abs(seg).max())
        if pk > .99: seg = seg * (.99 / pk)   # crossfade can sum above full scale
        ogg = encode(seg); res[did] = dict(dur=round(n / fps, 4), data='data:audio/ogg;base64,' + base64.b64encode(ogg).decode())
        print(did, 'loop', i, j, '%.2f s' % (n / fps), '%d KB' % (len(ogg) // 1024))
    js = ('/* generated by tools/roto/dance_audio.py: dance music cut to each clip\'s loop window (same seam blend as the motion); played by web/src3d/dance_audio3d.js */\n'
          'window.RB_DANCE_AUDIO=' + json.dumps(res, separators=(',', ':')) + ';\n')
    open(OUT, 'w', encoding='utf-8').write(js); print('wrote', OUT, round(os.path.getsize(OUT) / 1e6, 2), 'MB', sorted(res))

if __name__ == '__main__': main()
